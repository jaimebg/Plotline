import Foundation

/// Chooses the discovered seeds. Pure: pages in, ids out, so every rule here
/// is tested without the network.
enum SeedSelector {
    /// No episode arc to analyse. Same exclusions the hand-built list used.
    static let excludedGenres: Set<Int> = [10763, 10764, 10767]  // News, Reality, Talk

    /// TV genres the dataset tries to cover in depth. Every genre the Analysis
    /// tab can show a chip for, minus the excluded ones and Soap (whose
    /// listings are dominated by long-running dailies the engine mostly skips).
    static let flooredGenres: [Int] = [10759, 16, 35, 80, 99, 18, 10751, 10762, 9648, 10765, 10768, 37]

    static let target = 1_000

    /// Seeds per genre. At the current skip rate this aims for about 25
    /// analysed series per genre — a target, not a promise.
    static let genreFloor = 40

    struct Selection: Equatable {
        /// Popular picks first, then top-ups, in the order chosen.
        let seeds: [SeedCandidate]
        /// Floored genres still short after every top-up, with their counts.
        let shortGenres: [Int: Int]
    }

    static func isEligible(_ candidate: SeedCandidate) -> Bool {
        excludedGenres.isDisjoint(with: candidate.genreIds)
    }

    /// Fills to `target` (hand-picked included) from `popular`, then tops up
    /// each floored genre from `byGenre` until it holds `genreFloor` seeds.
    /// Hand-picked ids count toward no floor: their genres are not known here.
    static func select(
        handPicked: [Int],
        excluded: Set<Int>,
        popular: [SeedCandidate],
        byGenre: [Int: [SeedCandidate]],
        target: Int = target,
        genreFloor: Int = genreFloor
    ) -> Selection {
        var taken = Set(handPicked).union(excluded)
        var seeds: [SeedCandidate] = []

        func take(_ candidate: SeedCandidate) -> Bool {
            guard isEligible(candidate), !taken.contains(candidate.id) else { return false }
            taken.insert(candidate.id)
            seeds.append(candidate)
            return true
        }

        let quota = max(target - handPicked.count, 0)
        for candidate in popular {
            guard seeds.count < quota else { break }
            _ = take(candidate)
        }

        var counts: [Int: Int] = [:]
        for genre in flooredGenres {
            counts[genre] = seeds.filter { $0.genreIds.contains(genre) }.count
        }

        for genre in flooredGenres {
            for candidate in byGenre[genre] ?? [] {
                guard counts[genre, default: 0] < genreFloor else { break }
                if take(candidate) {
                    for carried in candidate.genreIds where counts[carried] != nil {
                        counts[carried, default: 0] += 1
                    }
                }
            }
        }

        return Selection(seeds: seeds, shortGenres: counts.filter { $0.value < genreFloor })
    }

    /// The whole of `SeedList.swift`.
    static func render(_ seeds: [SeedCandidate]) -> String {
        var lines = [
            "import Foundation",
            "",
            "/// TMDB series ids baked into the dataset, after the hand-picked ones in",
            "/// `SeedCuration`.",
            "///",
            "/// Generated by `dataset-generator seed` from TMDB's most-voted series, each",
            "/// floored genre topped up to `SeedSelector.genreFloor`. Re-running the",
            "/// subcommand rewrites this file: to drop a series for good, add its id to",
            "/// `SeedCuration.excludedIds` rather than deleting its line here.",
            "///",
            "/// Ordering does not affect the output: `DatasetBuilder` sorts by id.",
            "enum SeedList {",
            "    static let discoveredIds: [Int] = [",
        ]
        for seed in seeds {
            let name = seed.name
                .replacingOccurrences(of: "\r", with: " ")
                .replacingOccurrences(of: "\n", with: " ")
            lines.append("        \(seed.id),  // \(name)")
        }
        lines += [
            "    ]",
            "",
            "    static var seriesIds: [Int] { SeedCuration.handPickedIds + discoveredIds }",
            "}",
            "",
        ]
        return lines.joined(separator: "\n")
    }
}
